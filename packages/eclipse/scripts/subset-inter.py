"""Rebuild vendored Inter subsets; use fonttools[woff]==4.60.2.

Keep the original font files for compatibility. Every original Unicode point,
variable axis, advance metric and OpenType feature remains available. This is
an asset-maintenance command, not a build/runtime Python dependency.
"""
from pathlib import Path
import hashlib
import json
from fontTools import subset
from fontTools.ttLib import TTFont

root = Path(__file__).resolve().parents[1]
fonts = root / "src/static/fonts"
out = fonts / "subsets"
out.mkdir(exist_ok=True)
latin_ranges = [(0, 0xFF), (0x131, 0x131), (0x152, 0x153), (0x2BB, 0x2BC),
                (0x2C6, 0x2C6), (0x2DA, 0x2DA), (0x2DC, 0x2DC),
                (0x2000, 0x206F), (0x20AC, 0x20AC), (0x2122, 0x2122),
                (0x2191, 0x2193), (0x2212, 0x2212), (0x2215, 0x2215),
                (0xFEFF, 0xFEFF), (0xFFFD, 0xFFFD)]

def group(point):
    if any(lo <= point <= hi for lo, hi in latin_ranges):
        return "latin"
    if 0x400 <= point <= 0x52F or 0x2DE0 <= point <= 0x2DFF or 0xA640 <= point <= 0xA69F:
        return "cyrillic"
    if 0x370 <= point <= 0x3FF or 0x1F00 <= point <= 0x1FFF:
        return "greek"
    if 0x100 <= point <= 0x36F or 0x1D00 <= point <= 0x1EFF or 0x2C60 <= point <= 0x2C7F or 0xA720 <= point <= 0xA7FF:
        return "latin-ext"
    return "symbols"

def ranges(points):
    runs = []
    for point in sorted(points):
        if runs and point == runs[-1][1] + 1:
            runs[-1][1] = point
        else:
            runs.append([point, point])
    return ", ".join("U+%X" % a if a == b else "U+%X-%X" % (a, b) for a, b in runs)

digest = lambda data: hashlib.sha256(data).hexdigest()
css = ["/* Generated by scripts/subset-inter.py; original glyph coverage retained. */"]
manifest = []
for name, style in [("InterVariable", "normal"), ("InterVariable-Italic", "italic")]:
    source = fonts / (name + ".woff2")
    original = TTFont(source)
    coverage = set(original.getBestCmap())
    union = set()
    for category in ["latin", "latin-ext", "greek", "cyrillic", "symbols"]:
        points = {point for point in coverage if group(point) == category}
        font = TTFont(source)
        options = subset.Options()
        options.layout_features = ["*"]
        options.name_IDs = ["*"]
        options.name_legacy = True
        options.name_languages = ["*"]
        options.recalc_timestamp = False
        subsetter = subset.Subsetter(options=options)
        # Keep combining marks in each binary so mixed-script grapheme clusters
        # retain their original shaping; CSS ranges select by the base script.
        shaping = {point for point in coverage if 0x300 <= point <= 0x36F}
        subsetter.populate(unicodes=points | shaping)
        subsetter.subset(font)
        font.flavor = "woff2"
        target = out / (name + "-" + category + ".woff2")
        font.save(target)
        actual = TTFont(target)
        assert points <= set(actual.getBestCmap())
        assert [(a.axisTag, a.minValue, a.defaultValue, a.maxValue) for a in actual["fvar"].axes] == [(a.axisTag, a.minValue, a.defaultValue, a.maxValue) for a in original["fvar"].axes]
        for point in points:
            assert actual["hmtx"].metrics[actual.getBestCmap()[point]][0] == original["hmtx"].metrics[original.getBestCmap()[point]][0]
        union |= points
        css.append(f'''@font-face {{
  font-family: "Inter";
  src: url("../static/fonts/subsets/{target.name}") format("woff2-variations");
  font-weight: 100 900;
  font-style: {style};
  font-display: swap;
  unicode-range: {ranges(points)};
}}''')
        manifest.append(dict(file=target.name, bytes=target.stat().st_size,
                             sha256=digest(target.read_bytes()), source=source.name,
                             sourceSha256=digest(source.read_bytes()), points=len(points)))
        print(target.name, target.stat().st_size)
    assert union == coverage, "Subsets must preserve every original character"
(root / "src/styles/inter-subsets.css").write_text("\n\n".join(css) + "\n")
(out / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")

# Next's bracketed filename produced distinct encoded preload and CSS URLs.
# Preserve the original export and make the URL-safe alias byte-identical.
(fonts / "MonaSansMonoVF.woff2").write_bytes((fonts / "MonaSansMonoVF[wght].woff2").read_bytes())

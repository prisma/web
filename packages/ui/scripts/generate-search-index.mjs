import { readdir, readFile, writeFile, rename } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";
import { parse } from "yaml";

const root = fileURLToPath(new URL("../../../", import.meta.url));
async function files(dir) {
  return (
    await Promise.all(
      (
        await readdir(dir, { withFileTypes: true })
      )
        .sort((a, b) => a.name.localeCompare(b.name))
        .map(async (entry) => {
          const name = path.join(dir, entry.name);
          return entry.isDirectory() ? files(name) : [name];
        }),
    )
  ).flat();
}
const clean = (text) =>
  String(text ?? "")
    .replace(/```[\s\S]*?```/g, " ")
    .replace(/<[^>]*>/g, " ")
    .replace(/!?\[([^\]]*)\]\([^)]*\)/g, "$1")
    .replace(/[#*`{}]/g, "")
    .replace(/\s+/g, " ")
    .trim();
const entries = [];
for (const [source, folder, prefix] of [
  ["docs", "apps/docs/content/docs", "/docs"],
  ["blog", "apps/blog/content/blog", "/blog"],
  ["website", "apps/site/content/changelog", "/changelog"],
]) {
  const dir = path.join(root, folder);
  for (const file of await files(dir)) {
    if (!/\.mdx?$/.test(file)) continue;
    const raw = await readFile(file, "utf8");
    const match = raw.match(/^---\r?\n([\s\S]*?)\r?\n---/);
    if (!match) continue;
    const data = parse(match[1]);
    if (!data?.title || data.draft === true || data.published === false) continue;
    const relative = path
      .relative(dir, file)
      .replace(/\\/g, "/")
      .replace(/\.mdx?$/, "")
      .split("/")
      .filter((p) => !/^\(.*\)$/.test(p))
      .join("/")
      .replace(/(^|\/)index$/, "");
    // Docs frontmatter includes legacy public aliases; the file path is the loader's canonical route.
    const slug = source === "blog" ? data.slug || relative : relative;
    const url = `${prefix}/${String(slug).replace(/^\/+/, "")}`.replace(/\/$/, "");
    const body = clean(raw.slice(match[0].length));
    entries.push({
      source,
      url,
      title: clean(data.title),
      description: clean(data.metaDescription || data.description || data.excerpt || body).slice(
        0,
        220,
      ),
      keywords: [...new Set(body.toLowerCase().match(/[\p{L}\p{N}_-]{2,}/gu) || [])]
        .join(" ")
        .slice(0, 5000),
    });
  }
}
const siteDir = path.join(root, "apps/site/src/app");
for (const file of await files(siteDir)) {
  if (!file.endsWith("/page.tsx")) continue;
  const parts = path.relative(siteDir, path.dirname(file)).split(path.sep).filter(Boolean);
  if (parts.some((p) => p.includes("[") || p.startsWith("_") || ["demo", "newsletter"].includes(p)))
    continue;
  const url = "/" + parts.filter((p) => !p.startsWith("(")).join("/");
  const raw = await readFile(file, "utf8");
  const title =
    raw.match(/\btitle:\s*["'`]([^"'`]+)["'`]/)?.[1] ||
    (url === "/"
      ? "Prisma — Build, deploy, and manage your app"
      : parts
          .at(-1)
          .replace(/-/g, " ")
          .replace(/\b\w/g, (c) => c.toUpperCase()));
  const description =
    raw.match(/\bdescription:\s*["'`]([^"'`]+)["'`]/)?.[1] || `Explore ${title} on Prisma.`;
  entries.push({
    source: "website",
    url,
    title,
    description,
    keywords: clean(raw.replace(/^import .*$/gm, ""))
      .toLowerCase()
      .slice(0, 2500),
  });
}
const unique = [...new Map(entries.map((e) => [e.url, e])).values()];
const output =
  "// Generated by packages/ui/scripts/generate-search-index.mjs. Do not edit.\nexport default " +
  JSON.stringify(unique) +
  ";\n";
const target = path.join(root, "packages/ui/src/lib/search-index.ts");
const current = await readFile(target, "utf8").catch(() => "");
if (current !== output) {
  const temporary = `${target}.${process.pid}.tmp`;
  await writeFile(temporary, output);
  await rename(temporary, target);
}
console.log(
  `Indexed ${unique.length} public pages: ${["website", "docs", "blog"].map((s) => `${unique.filter((e) => e.source === s).length} ${s}`).join(", ")}.`,
);
